package com.example.nutrimpact;

import androidx.room.ColumnInfo;
import androidx.room.Entity;
import androidx.room.Index;
import androidx.room.PrimaryKey;

/**
 * One row of the "food_log" table. Nutrition is stored per 100g together with
 * the portion size, so the portion can be edited later without losing accuracy;
 * the scaled values are worked out with PortionCalculator.
 */
@Entity(tableName = "food_log", indices = {@Index("log_date")})
public class FoodLogEntry {

    /** Unique ID, generated by the database. */
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "id")
    private long id;

    /** Product name as shown in search results. */
    @ColumnInfo(name = "product_name")
    private String productName;

    /** Brand names as one string, e.g. "Quaker, Quaker Oats". */
    @ColumnInfo(name = "brands")
    private String brands;

    /** Meal name, e.g. "BREAKFAST" (see MealType). */
    @ColumnInfo(name = "meal_type")
    private String mealType;

    /** Day the food was eaten, as days since 1970-01-01 (LocalDate.toEpochDay()). */
    @ColumnInfo(name = "log_date")
    private long logDate;

    /** When the entry was added, in milliseconds since 1970-01-01 UTC. */
    @ColumnInfo(name = "logged_at")
    private long loggedAt;

    /** Portion size in grams. */
    @ColumnInfo(name = "portion_grams")
    private double portionGrams;

    /** Calories per 100g. */
    @ColumnInfo(name = "calories_per_100g")
    private double caloriesPer100g;

    /** Protein in grams per 100g. */
    @ColumnInfo(name = "protein_per_100g")
    private double proteinPer100g;

    /** Carbohydrates in grams per 100g. */
    @ColumnInfo(name = "carbs_per_100g")
    private double carbsPer100g;

    /** Fat in grams per 100g. */
    @ColumnInfo(name = "fat_per_100g")
    private double fatPer100g;

    /**
     * Default constructor, required by Room.
     */
    public FoodLogEntry() {
    }

    /**
     * Gets the entry's database ID.
     *
     * @return the ID, or 0 if not saved yet.
     */
    public long getId() {
        return id;
    }

    /**
     * Sets the entry's database ID. Normally only Room calls this.
     *
     * @param id the ID.
     */
    public void setId(long id) {
        this.id = id;
    }

    /**
     * Gets the product name.
     *
     * @return the product name.
     */
    public String getProductName() {
        return productName;
    }

    /**
     * Sets the product name.
     *
     * @param productName the product name.
     */
    public void setProductName(String productName) {
        this.productName = productName;
    }

    /**
     * Gets the brand names.
     *
     * @return the brands as one string.
     */
    public String getBrands() {
        return brands;
    }

    /**
     * Sets the brand names.
     *
     * @param brands the brands as one string.
     */
    public void setBrands(String brands) {
        this.brands = brands;
    }

    /**
     * Gets the stored meal name.
     *
     * @return the meal name, e.g. "BREAKFAST".
     */
    public String getMealType() {
        return mealType;
    }

    /**
     * Sets the stored meal name.
     *
     * @param mealType the meal name, e.g. "BREAKFAST".
     */
    public void setMealType(String mealType) {
        this.mealType = mealType;
    }

    /**
     * Gets the day the food was eaten.
     *
     * @return days since 1970-01-01.
     */
    public long getLogDate() {
        return logDate;
    }

    /**
     * Sets the day the food was eaten.
     *
     * @param logDate days since 1970-01-01.
     */
    public void setLogDate(long logDate) {
        this.logDate = logDate;
    }

    /**
     * Gets when the entry was added.
     *
     * @return milliseconds since 1970-01-01 UTC.
     */
    public long getLoggedAt() {
        return loggedAt;
    }

    /**
     * Sets when the entry was added.
     *
     * @param loggedAt milliseconds since 1970-01-01 UTC.
     */
    public void setLoggedAt(long loggedAt) {
        this.loggedAt = loggedAt;
    }

    /**
     * Gets the portion size.
     *
     * @return the portion in grams.
     */
    public double getPortionGrams() {
        return portionGrams;
    }

    /**
     * Sets the portion size.
     *
     * @param portionGrams the portion in grams.
     */
    public void setPortionGrams(double portionGrams) {
        this.portionGrams = portionGrams;
    }

    /**
     * Gets calories per 100g.
     *
     * @return calories in kcal per 100g.
     */
    public double getCaloriesPer100g() {
        return caloriesPer100g;
    }

    /**
     * Sets calories per 100g.
     *
     * @param caloriesPer100g calories in kcal per 100g.
     */
    public void setCaloriesPer100g(double caloriesPer100g) {
        this.caloriesPer100g = caloriesPer100g;
    }

    /**
     * Gets protein per 100g.
     *
     * @return protein in grams per 100g.
     */
    public double getProteinPer100g() {
        return proteinPer100g;
    }

    /**
     * Sets protein per 100g.
     *
     * @param proteinPer100g protein in grams per 100g.
     */
    public void setProteinPer100g(double proteinPer100g) {
        this.proteinPer100g = proteinPer100g;
    }

    /**
     * Gets carbohydrates per 100g.
     *
     * @return carbohydrates in grams per 100g.
     */
    public double getCarbsPer100g() {
        return carbsPer100g;
    }

    /**
     * Sets carbohydrates per 100g.
     *
     * @param carbsPer100g carbohydrates in grams per 100g.
     */
    public void setCarbsPer100g(double carbsPer100g) {
        this.carbsPer100g = carbsPer100g;
    }

    /**
     * Gets fat per 100g.
     *
     * @return fat in grams per 100g.
     */
    public double getFatPer100g() {
        return fatPer100g;
    }

    /**
     * Sets fat per 100g.
     *
     * @param fatPer100g fat in grams per 100g.
     */
    public void setFatPer100g(double fatPer100g) {
        this.fatPer100g = fatPer100g;
    }

    /**
     * Gets the calories for this portion.
     *
     * @return calories in kcal for the logged portion.
     */
    public double getPortionCalories() {
        return PortionCalculator.scale(caloriesPer100g, portionGrams);
    }

    /**
     * Gets the protein for this portion.
     *
     * @return protein in grams for the logged portion.
     */
    public double getPortionProtein() {
        return PortionCalculator.scale(proteinPer100g, portionGrams);
    }

    /**
     * Gets the carbohydrates for this portion.
     *
     * @return carbohydrates in grams for the logged portion.
     */
    public double getPortionCarbs() {
        return PortionCalculator.scale(carbsPer100g, portionGrams);
    }

    /**
     * Gets the fat for this portion.
     *
     * @return fat in grams for the logged portion.
     */
    public double getPortionFat() {
        return PortionCalculator.scale(fatPer100g, portionGrams);
    }
}
